import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "vite";
import solid from "vite-plugin-solid";
import { solidOptions } from "../scripts/solid-options";
import { clientDocument, elements } from "./support/client-dom";
import { parseHtml } from "./support/queries";

type Probe = typeof import("./fixtures/icons");
let server: Probe, client: Probe;
const directory = mkdtempSync(join(tmpdir(), "bindery-icons-"));
const disposers: (() => void)[] = [];

function browserGlobals() {
  const document = clientDocument(), body = document.createElement("body");
  document.documentElement.appendChild(body);
  Object.defineProperty(document, "body", { configurable: true, value: body });
  document.addEventListener = vi.fn(); document.removeEventListener = vi.fn();
  vi.stubGlobal("document", document); vi.stubGlobal("self", globalThis);
}
function snapshot(root: Element) {
  return elements(root, "*").map(element => [element.localName, Array.from(element.attributes)
    .filter(attribute => attribute.name !== "_hk")
    .map(attribute => [attribute.name, attribute.value])
    .sort((a, b) => a[0]!.localeCompare(b[0]!))]);
}

beforeEach(browserGlobals);
beforeAll(async () => {
  browserGlobals();
  for (const ssr of [true, false]) {
    const entry = resolve("tests-ts/fixtures/icons.tsx");
    const result = await build({ configFile: false, logLevel: "silent", plugins: [solid({ ...solidOptions, dev: false, hot: false })],
      resolve: { conditions: ssr ? ["node", "production"] : ["browser", "production"] }, define: { "process.env.NODE_ENV": '"production"' }, ssr: { noExternal: true },
      build: { write: false, minify: true, ...(ssr ? { ssr: entry } : { lib: { entry, formats: ["es"] } }) } });
    const chunk = (Array.isArray(result) ? result : [result]).flatMap(output => "output" in output ? output.output : []).find(output => output.type === "chunk" && output.isEntry);
    if (!chunk || chunk.type !== "chunk") throw new Error("Missing icon probe");
    const path = join(directory, ssr ? "server.mjs" : "client.mjs"); writeFileSync(path, chunk.code);
    const module: Probe = await import(/* @vite-ignore */ pathToFileURL(path).href);
    if (ssr) server = module; else client = module;
  }
});
afterEach(() => { disposers.splice(0).reverse().forEach(dispose => dispose()); vi.unstubAllGlobals(); });
afterAll(() => rmSync(directory, { recursive: true, force: true }));

describe("generated Tabler data", () => {
  it("is regenerated whenever the generator icon list changes", () => {
    expect(execFileSync(process.execPath, ["scripts/gen-icons.mjs", "--check"], { encoding: "utf8" })).toContain("up to date");
    const generated = readFileSync("src/ui/icon-data.ts", "utf8");
    expect(generated).toContain("Generated by scripts/gen-icons.mjs");
    expect(generated).toMatch(/@iconify-json\/tabler \d+\.\d+\.\d+ \(Tabler Icons \d+\.\d+\.\d+\), MIT licensed/);
    expect(generated).not.toContain('stroke-width="2"');
  });
});

describe("Icon rendering", () => {
  it("renders decorative icons by default and names only labelled icons", () => {
    const root = parseHtml(server.markup()), icons = elements(root, "svg");
    expect(icons).toHaveLength(3);
    const [decorative, labelled, compact] = icons;
    expect(decorative!.getAttribute("viewBox")).toBe("0 0 24 24");
    expect([decorative!.getAttribute("width"), decorative!.getAttribute("height")]).toEqual(["20", "20"]);
    expect(decorative!.getAttribute("fill")).toBe("none");
    expect(decorative!.getAttribute("stroke-width")).toBe("1.7");
    expect(decorative!.getAttribute("focusable")).toBe("false");
    expect(decorative!.getAttribute("aria-hidden")).toBe("true");
    expect(decorative!.hasAttribute("role")).toBe(false);
    expect(decorative!.hasAttribute("aria-label")).toBe(false);
    expect(decorative!.getElementsByTagName("path").length).toBeGreaterThan(0);

    expect([labelled!.getAttribute("width"), labelled!.getAttribute("height")]).toEqual(["28", "28"]);
    expect(labelled!.getAttribute("stroke-width")).toBe("2.25");
    expect(labelled!.getAttribute("class")).toBe("custom-icon");
    expect(labelled!.getAttribute("role")).toBe("img");
    expect(labelled!.getAttribute("aria-label")).toBe("已收藏");
    expect(labelled!.hasAttribute("aria-hidden")).toBe(false);

    expect([compact!.getAttribute("width"), compact!.getAttribute("height")]).toEqual(["16", "16"]);
    expect(compact!.getAttribute("stroke-width")).toBe("1.2");
    expect(server.markup()).not.toContain('stroke-width="2"');
  });

  it("hydrates to the same SVG tree as the server render", () => {
    const node = document.createElement("div");
    document.documentElement.appendChild(node);
    node.innerHTML = server.markup();
    const before = snapshot(node);
    vi.stubGlobal("_$HY", { r: {}, completed: new WeakSet(), events: [] });
    const mounted = client.mount(node as HTMLElement);
    disposers.push(() => node.remove(), mounted.dispose);
    mounted.flush();
    expect(snapshot(node)).toEqual(before);
    expect(elements(node, "svg")).toHaveLength(3);
    expect(elements(node, "path").length + elements(node, "g").length).toBeGreaterThan(0);
  });
});
