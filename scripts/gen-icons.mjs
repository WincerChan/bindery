function readJson(id) {
  return JSON.parse(readFileSync(require.resolve(id), "utf8"));
}

export function generateIconData() {
  const icons = readJson("@iconify-json/tabler/icons.json").icons;
  const info = readJson("@iconify-json/tabler/info.json");
  const pkg = readJson("@iconify-json/tabler/package.json");
  const duplicates = ICON_NAMES.filter((name, index) => ICON_NAMES.indexOf(name) !== index);
  if (duplicates.length) throw new Error(`Duplicate icon names: ${[...new Set(duplicates)].join(", ")}`);
  const unknown = ICON_NAMES.filter(name => !icons[name]);
  if (unknown.length) throw new Error(`Unknown @iconify-json/tabler icon names: ${unknown.join(", ")}`);
  const entries = [...ICON_NAMES].sort().map(name => {
    const body = icons[name].body.replace(/\s+stroke-width="2"/g, "");
    if (body.includes('stroke-width="2"')) throw new Error(`Could not strip stroke-width from ${name}`);
    return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
  });
  return [
    "// Generated by scripts/gen-icons.mjs. Do not edit by hand.",
    `// Source: @iconify-json/tabler ${pkg.version} (Tabler Icons ${info.version}), MIT licensed.`,
    "// Tabler Icons license: https://github.com/tabler/tabler-icons/blob/master/LICENSE",
    "",
    "export const iconBodies = {",
    ...entries,
    "} as const;",
    "",
    "export type IconName = keyof typeof iconBodies;",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = generateIconData();
  if (process.argv.includes("--check")) {
    const current = readFileSync(output, "utf8");
    if (current !== generated) {
      console.error("src/ui/icon-data.ts is out of date. Run: node scripts/gen-icons.mjs");
      process.exitCode = 1;
    } else {
      console.log(`icon data is up to date (${ICON_NAMES.length} icons)`);
    }
  } else {
    writeFileSync(output, generated);
    console.log(`wrote src/ui/icon-data.ts (${ICON_NAMES.length} icons)`);
  }
}
